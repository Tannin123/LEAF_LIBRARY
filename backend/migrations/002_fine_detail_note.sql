CREATE OR REPLACE VIEW chitietphieuphat AS
SELECT "maChiTietPhat" AS machitietphat,
       "maPhieuPhat" AS maphieuphat,
       "maChiTietMuon" AS machitietmuon,
       "loaiViPham" AS loaivipham,
       "soNgayQuaHan" AS songayquahan,
       "mucDoHuHong" AS mucdohuhong,
       "soTienPhat" AS sotienphat,
       "ghiChu" AS ghichu
FROM "CHITIETPHIEUPHAT";
